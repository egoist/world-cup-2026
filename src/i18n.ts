export type Locale = "zh" | "en" | "ja"

export const localeStorageKey = "world-cup-2026-predictor-locale"

export const locales: { id: Locale; label: string; htmlLang: string }[] = [
  { id: "zh", label: "中文", htmlLang: "zh-CN" },
  { id: "en", label: "English", htmlLang: "en" },
  { id: "ja", label: "日本語", htmlLang: "ja" },
]

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && locales.some((locale) => locale.id === value)
}

function getBrowserLocale(): Locale {
  if (typeof navigator === "undefined") return "en"
  const language = navigator.language.toLowerCase()
  if (language.startsWith("ja")) return "ja"
  if (language.startsWith("zh")) return "zh"
  return "en"
}

function getInitialLocale() {
  if (typeof localStorage === "undefined") return getBrowserLocale()
  const savedLocale = localStorage.getItem(localeStorageKey)
  return isLocale(savedLocale) ? savedLocale : getBrowserLocale()
}

